def get_asset_bytes(name: str) -> bytes:
    """Return one verified WebUI asset from the embedded bundle."""
    digest, expected_size, payload = _ASSETS[name]
    compact = b"".join(payload.split())
    data = zlib.decompress(base64.b85decode(compact))
    if len(data) != expected_size or hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"Embedded WebUI asset failed integrity check: {name}")
    return data
